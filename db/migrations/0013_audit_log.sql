CREATE OR REPLACE FUNCTION audit_summary_refresh(p_day date DEFAULT current_date)
RETURNS bigint LANGUAGE plpgsql VOLATILE AS $$
DECLARE
    v_rows bigint;
BEGIN
    -- SECURITY INVOKER on purpose: under 0009's wall an agent connection aggregates its
    -- own tenant's sessions, which is the only semantics that makes total_sessions true per
    -- tenant without a GROUP BY nobody asked for. Run as owner by a scheduler and it
    -- refreshes every tenant; run as afpc_app and it refreshes one, honestly.
    WITH sess AS (
        SELECT user_id, bot_id,
               count(*) AS n,
               avg(extract(epoch FROM logout_time - login_time) / 60.0)
                   FILTER (WHERE logout_time IS NOT NULL) AS mins
          FROM human_sessions
         WHERE login_time::date = p_day
         GROUP BY user_id, bot_id
    ), act AS (
        SELECT user_id, bot_id,
               count(*) AS n,
               count(*) FILTER (WHERE success) AS ok,
               count(*) FILTER (WHERE NOT success) AS bad
          FROM bot_actions
         WHERE "timestamp"::date = p_day
         GROUP BY user_id, bot_id
    )
    INSERT INTO audit_summary
        ("date", user_id, bot_id, total_sessions, total_actions,
         successful_actions, failed_actions, avg_session_duration_minutes)
    SELECT p_day, user_id, bot_id,
           coalesce(sess.n, 0), coalesce(act.n, 0),
           coalesce(act.ok, 0), coalesce(act.bad, 0),
           round(sess.mins, 2)
      FROM sess FULL OUTER JOIN act USING (user_id, bot_id)
     ON CONFLICT (tenant_id, "date", user_id, bot_id) DO UPDATE
        SET total_sessions = EXCLUDED.total_sessions,
            total_actions  = EXCLUDED.total_actions,
            successful_actions = EXCLUDED.successful_actions,
            failed_actions = EXCLUDED.failed_actions,
            avg_session_duration_minutes = EXCLUDED.avg_session_duration_minutes;
    GET DIAGNOSTICS v_rows = ROW_COUNT;
    RETURN v_rows;
END
$$;

COMMENT ON FUNCTION audit_summary_refresh(date) IS
    'Recomputes one day of audit_summary from human_sessions and bot_actions. The arbiter is '
    'the 0003 tenant-scoped unique, spelled with tenant_id in the ON CONFLICT target (0004''s '
    'inference rule: the key is matched as a SET, and a 3-column target cannot reach a '
    '4-column index). This is the rollup 6.2 found with no writer at all - wiring it here is '
    'what 0010 predicted would trip B24, and the column + trigger above are the answer that '
    'promise prescribed. vw_idempotency_status reads the ON CONFLICT and classes it pattern 1 '
    'without being told; probe H asserts the classification so a register that stopped '
    'reading bodies cannot drift quietly. Re-running a day is safe by construction, which is '
    'the point of pattern 1.';

-- ---------------------------------------------------------------------------
-- 5. Verifying the chain, and publishing what is covered
-- ---------------------------------------------------------------------------
-- RETURNS TABLE columns are output variables; the loop assigns them and flushes one row per
-- (tenant, month) SEGMENT at each boundary. The whole row travels to the hasher as a true
-- audit_log composite (SELECT a FROM audit_log a), so verifier and writer hash the same
-- expression by construction - B25's principle, applied to a hash: two definitions of "the
-- payload" is how a chain becomes folklore.
CREATE OR REPLACE FUNCTION audit_chain_verify(p_tenant uuid DEFAULT NULL)
RETURNS TABLE (audit_tenant uuid, segment_start timestamptz, audited_rows bigint,
               chain_ok boolean, broken_at bigint, reason text)
LANGUAGE plpgsql STABLE AS $$
DECLARE
    r      record;
    v_prev text;
    v_key  text;
BEGIN
    -- p_tenant NULL verifies everything the calling role can SEE. As afpc_app that is
    -- precisely the chain it could tamper with, which is the honest unit of the question;
    -- the function proves nothing about rows the wall hides, and says so by returning no
    -- segment for them rather than an ok one.
    FOR r IN
        SELECT a.tenant_id AS seg_tenant,
               date_trunc('month', a.occurred_at) AS seg_month,
               a.audit_id, a.prev_hash, a.row_hash,
               a           AS whole
          FROM audit_log a
         WHERE p_tenant IS NULL OR a.tenant_id = p_tenant
         ORDER BY a.tenant_id, date_trunc('month', a.occurred_at), a.audit_id
    LOOP
        IF v_key IS DISTINCT FROM (r.seg_tenant || '@' || r.seg_month)::text THEN
            IF v_key IS NOT NULL THEN
                RETURN NEXT;                       -- flush the finished segment
            END IF;
            audit_tenant  := r.seg_tenant;
            segment_start := r.seg_month;
            audited_rows  := 0;
            chain_ok      := true;
            broken_at     := NULL;
            reason        := NULL;
            v_key := (r.seg_tenant || '@' || r.seg_month)::text;
            v_prev := afpc_audit_genesis(r.seg_tenant, r.seg_month);
        END IF;

        audited_rows := audited_rows + 1;

        IF chain_ok THEN
            IF r.prev_hash IS DISTINCT FROM v_prev THEN
                chain_ok  := false;
                broken_at := r.audit_id;
                reason := 'prev_hash does not continue the segment - rows were written out '
                          'of chain order, or a row was deleted from between two others';
            ELSIF afpc_audit_hash(r.whole) IS DISTINCT FROM r.row_hash THEN
                chain_ok  := false;
                broken_at := r.audit_id;
                reason := 'row_hash does not match a recomputation from the stored columns '
                          '- this row was rewritten in place';
            END IF;
            v_prev := r.row_hash;
        END IF;
    END LOOP;

    IF v_key IS NOT NULL THEN
        RETURN NEXT;                               -- flush the last segment
    END IF;
END
$$;

COMMENT ON FUNCTION audit_chain_verify(uuid) IS
    'Recomputes every audit row''s hash through afpc_audit_hash - the identical expression '
    'the trigger used - and re-links prev_hash, one result row per (tenant, month) segment. '
    'The three tamper modes are caught separately: rewriting a row fails the recomputation, '
    'deleting one fails the next row''s prev_hash, forging an insert fails its own. STABLE '
    'and SECURITY INVOKER: an auditor sees its visible tenants'' chains and nothing else, '
    'which is stated because a verify result is only ever as wide as the caller''s '
    'visibility. Built by 0013.';

-- ---------------------------------------------------------------------------
-- 5b. vw_audit_coverage: which tables have a trail, and which said no, with why
-- ---------------------------------------------------------------------------
CREATE OR REPLACE VIEW vw_audit_coverage AS
    WITH scope AS (
        SELECT c.oid, c.relname
          FROM pg_class c
          JOIN pg_namespace ns ON ns.oid = c.relnamespace
          JOIN pg_attribute a ON a.attrelid = c.oid
                             AND a.attname = 'tenant_id' AND a.attnum > 0
                             AND NOT a.attisdropped
         WHERE ns.nspname = 'public' AND c.relkind = 'r'
           AND c.relname <> 'schema_migrations'
    )
    SELECT s.relname AS table_name,
           (tg.tgname IS NOT NULL)                 AS row_audited,
           s.relname IN ('audit_log', 'idempotency_keys') AS exempted,
           CASE
             WHEN s.relname = 'audit_log'
                 THEN 'exempt - recursion: the audit insert would fire the audit trigger'
             WHEN s.relname = 'idempotency_keys'
                 THEN 'exempt - transient mechanism state (ADR-005 TTL rows are themselves '
                      'the claim evidence; auditing the guard doubles every write''s cost)'
             WHEN s.relname IN ('bot_actions', 'human_sessions', 'agent_interactions')
                 THEN 'audited IN SCOPE ON PURPOSE - 6.2''s completeness: telemetry rows are '
                      'what an auditor cross-checks the trail against'
             ELSE 'business fact - in scope by the tenant-coded census'
           END                                     AS decision
      FROM scope s
      LEFT JOIN pg_trigger tg
             ON tg.tgrelid = s.oid AND tg.tgname = 'afpc_audit_row' AND NOT tg.tgisinternal
     ORDER BY row_audited DESC, s.relname;

COMMENT ON VIEW vw_audit_coverage IS
    'One row per tenant-coded base table: whether an ordinary write leaves a trail. Scope is '
    'the catalog''s own definition (relkind r, has tenant_id) minus two named exemptions, so '
    'a new business table appears here UNAUDITED the moment a tenancy migration gives it the '
    'column - the same "the finding grows by following the plan" property as B7 and '
    'vw_timestamp_status. verify.sh B26 counts the disagreement between row_audited and '
    'exempted. Built by 0013.';

-- ---------------------------------------------------------------------------
-- 6. Forward-fix to vw_idempotency_status: a trigger function is not a callable operation
-- ---------------------------------------------------------------------------
-- The register joins "functions that write a table" from every non-extension function body,
-- and afpc_audit_row is the first trigger function that writes one: left alone, the register
-- would list it UNGUARDED - "a retry of this function performs the operation twice" - which
-- is wrong twice over. A trigger is never retried apart from the data operation it
-- accompanies, and that operation's own guard is exactly what the other rows track. ADR-005
-- scopes idempotency to operations; an AFTER-row trigger is not one.
--
-- The fix is applied by TRANSFORMING THE LIVE DEFINITION, not by re-pasting this file's
-- memory of it (0012's capture-prove pattern): one exact substring gains the filter, the
-- replacement is asserted to have happened exactly once, and if the definition ever stops
-- containing that substring the migration refuses to run rather than silently replacing a
-- register with an older draft of itself. The exclusion is by return type, not by name, so
-- the next mechanism that writes inherits it. Then 0009's rule: CREATE OR REPLACE dropped
-- the reloption, so it is set after, never before.
DO $$
DECLARE
    v_def  text;
    v_new  text;
    v_hits int;
BEGIN
    SELECT pg_get_viewdef('public.vw_idempotency_status'::regclass, false) INTO v_def;

    SELECT count(*) INTO v_hits
      FROM regexp_matches(v_def, 'p\.prokind', 'g');
    IF v_hits <> 1 THEN
        RAISE EXCEPTION 'the writers filter appears % times in the live register - the '
                        'transform assumes exactly one, and applying it to several would '
                        'change a predicate the migration has not read', v_hits;
    END IF;

    v_new := replace(v_def,
        'p.prokind = ''f''::"char"',
        'p.prokind = ''f''::"char" AND p.prorettype <> ''trigger''::regtype');
    IF v_new = v_def THEN
        RAISE EXCEPTION 'vw_idempotency_status''s writers filter rendered differently than '
                        'the transform targets - re-derive from the live definition, never '
                        'apply a forward-fix blind';
    END IF;

    EXECUTE 'CREATE OR REPLACE VIEW public.vw_idempotency_status AS ' || v_new;
    RAISE NOTICE '6.2: vw_idempotency_status forward-fixed in place (transform of the live '
                 'definition, not a re-paste) - trigger functions are mechanisms, not '
                 'callable operations (ADR-005 scope)';
END
$$;

-- The replace ate the reloption (0009's rule); re-set it immediately, and section 5c's
-- final sweep is the second lock.
ALTER VIEW vw_idempotency_status SET (security_invoker = true);

-- ---------------------------------------------------------------------------
-- 7. Function privileges, the way 0009 and 0010 taught them
-- ---------------------------------------------------------------------------
-- Functions are born EXECUTE-to-PUBLIC (0008's census; B22 is the backstop, ALTER DEFAULT
-- PRIVILEGES cannot do this - 0009 measured). The interesting one is the pair the TRIGGER
-- calls: a trigger function's own EXECUTE is not invoker-checked (0010 measured), but the
-- SQL it runs IS executed in the invoker's context - so an afpc_app write reaches
-- afpc_audit_hash/afpc_audit_genesis as afpc_app and dies with 'permission denied for
-- function' unless they are granted. The trigger function itself follows 0010's precedent
-- to the letter: revoked from PUBLIC, granted to nobody, fired only by the executor.
REVOKE EXECUTE ON FUNCTION afpc_audit_row()                      FROM PUBLIC;
REVOKE EXECUTE ON FUNCTION afpc_audit_hash(audit_log)            FROM PUBLIC;
REVOKE EXECUTE ON FUNCTION afpc_audit_genesis(uuid, timestamptz) FROM PUBLIC;
REVOKE EXECUTE ON FUNCTION audit_chain_verify(uuid)              FROM PUBLIC;
REVOKE EXECUTE ON FUNCTION audit_summary_refresh(date)           FROM PUBLIC;

GRANT EXECUTE ON FUNCTION afpc_audit_hash(audit_log)            TO afpc_app, afpc_readonly, afpc_auditor;
GRANT EXECUTE ON FUNCTION afpc_audit_genesis(uuid, timestamptz) TO afpc_app, afpc_readonly, afpc_auditor;
GRANT EXECUTE ON FUNCTION audit_chain_verify(uuid)              TO afpc_app, afpc_readonly, afpc_auditor;
-- The rollup is invoker-scoped, so agents may refresh their own tenant's day; scheduling
-- it is Phase 5's housekeeping, and 0011's sweep precedent (operator-only) is deliberately
-- NOT followed here because the aggregation is the agent's own data, not mechanism state.
GRANT EXECUTE ON FUNCTION audit_summary_refresh(date)           TO afpc_app;

-- ---------------------------------------------------------------------------
-- 8. Verify by behaving
-- ---------------------------------------------------------------------------
-- The seat rule every migration after 0009 obeys: a check of a control runs in the seat the
-- control binds. Coverage is a catalog claim (probe A); everything else about an audit trail
-- is what a WRITE does, so probes B onward change seats to afpc_app and only the
-- superuser-bypass demo (E) sits in the owner's chair, which is the only chair it can
-- demonstrate from. Fixtures are deleted afterwards; the audit rows about deleting them
-- stay, because that is the table being honest rather than residue.
DO $$
DECLARE
    v_ent     bigint;
    v_id      bigint;
    v_rows    bigint;
    v_ok      boolean;
    v_v       record;
    v_t1      uuid := '00000000-0000-0000-0000-000000000001';
    v_t2      uuid;
    v_n       int := 0;
    v_sess    uuid;
    v_ref     audit_log;
    v_why     text;
BEGIN
    ------------------------------------------------------------------
    -- A. coverage: nobody in scope is silent, nobody exempt is loud.
    ------------------------------------------------------------------
    SELECT count(*) INTO v_rows FROM vw_audit_coverage
     WHERE row_audited IS DISTINCT FROM (NOT exempted);
    IF v_rows <> 0 THEN
        RAISE EXCEPTION 'A failed: vw_audit_coverage disagrees with itself on % table(s)', v_rows;
    END IF;
    IF (SELECT count(*) FROM vw_audit_coverage WHERE exempted) <> 2 THEN
        RAISE EXCEPTION 'A failed: % exemptions registered, expected exactly the two named '
                        'in this file - the list and the trigger loop have diverged',
                        (SELECT count(*) FROM vw_audit_coverage WHERE exempted);
    END IF;
    v_n := v_n + 1;

    ------------------------------------------------------------------
    -- B. an ordinary write leaves an ordinary trail - in the seat the trail is for.
    ------------------------------------------------------------------
    SET LOCAL ROLE afpc_app;
    INSERT INTO entities (name, entity_type, status)
         VALUES ('0013 probe B', 'customer', 'active') RETURNING id INTO v_ent;
    UPDATE entities SET name = '0013 probe B renamed', status = 'inactive'
     WHERE id = v_ent;
    DELETE FROM entities WHERE id = v_ent;

    SELECT count(*) INTO v_rows FROM audit_log
     WHERE table_name = 'entities' AND row_pk->>'id' = v_ent::text;
    IF v_rows <> 3 THEN
        RAISE EXCEPTION 'B failed: three writes left % audit rows - the trail does not '
                        'follow ordinary DML', v_rows;
    END IF;

    SELECT (old_values ? 'name') AND (new_values ? 'name')
           AND NOT (old_values ? 'embedding') AND NOT (new_values ? 'embedding')
           AND (new_values ? 'status')
      INTO v_ok
      FROM audit_log
     WHERE table_name = 'entities' AND row_pk->>'id' = v_ent::text
       AND action = 'UPDATE';
    IF NOT v_ok THEN
        RAISE EXCEPTION 'B failed: the UPDATE audit row does not carry exactly the changed '
                        'columns without the vector - the diff half of 6.2 is decorative';
    END IF;

    IF (SELECT count(*) FROM audit_log
         WHERE table_name = 'entities' AND row_pk->>'id' = v_ent::text
           AND db_user = 'afpc_app') <> 3 THEN
        RAISE EXCEPTION 'B failed: the trail does not record the seat that actually sat - '
                        'db_user must be afpc_app here, which is 5.8''s identity answer in '
                        'one column';
    END IF;
    v_n := v_n + 1;

    ------------------------------------------------------------------
    -- C. append-only by grant: history cannot be rewritten from this seat.
    ------------------------------------------------------------------
    BEGIN
        UPDATE audit_log SET action = 'UPDATE'
         WHERE row_pk->>'id' = v_ent::text AND table_name = 'entities';
        RAISE EXCEPTION 'C failed: audit_log accepted an UPDATE from afpc_app - 2.6''s '
                        'no-UPDATE-grants requirement is not in effect';
    EXCEPTION
        WHEN insufficient_privilege THEN NULL;   -- the only correct outcome
    END;
    BEGIN
        DELETE FROM audit_log
         WHERE row_pk->>'id' = v_ent::text AND table_name = 'entities' AND action = 'INSERT';
        RAISE EXCEPTION 'C failed: audit_log accepted a DELETE from afpc_app - a role that '
                        'can delete history has no history';
    EXCEPTION
        WHEN insufficient_privilege THEN NULL;
    END;
    v_n := v_n + 1;

    ------------------------------------------------------------------
    -- D. the chain an agent can actually verify: its own, and only its own.
    ------------------------------------------------------------------
    SELECT coalesce(sum(audited_rows), 0), bool_and(chain_ok) INTO v_rows, v_ok
      FROM audit_chain_verify();
    IF v_rows < 3 OR NOT v_ok THEN
        RAISE EXCEPTION 'D failed: the invoker-visible chain did not verify (rows=% ok=%)',
            v_rows, v_ok;
    END IF;
    RESET ROLE;
    v_n := v_n + 1;

    ------------------------------------------------------------------
    -- E. the bypass it cannot prevent is the one it must expose: a superuser rewrite is
    --    silent in the table and loud in the chain. Then repaired, because this is the
    --    persistent server and the trail must end as true as it claimed to be.
    ------------------------------------------------------------------
    SELECT a.* INTO v_ref FROM audit_log a
     WHERE table_name = 'entities' AND row_pk->>'id' = v_ent::text AND action = 'UPDATE';
    UPDATE audit_log SET new_values = '{"tampered": true}'::jsonb WHERE audit_id = v_ref.audit_id;
    SELECT chain_ok, reason INTO v_ok, v_why
      FROM audit_chain_verify(v_t1)
     ORDER BY segment_start DESC LIMIT 1;
    IF v_ok THEN
        RAISE EXCEPTION 'E failed: a superuser rewrote an audit row and the chain still '
                        'verifies - the hash covers less than the columns it claims to';
    END IF;
    UPDATE audit_log SET new_values = (v_ref).new_values WHERE audit_id = v_ref.audit_id;
    SELECT chain_ok INTO v_ok FROM audit_chain_verify(v_t1)
     ORDER BY segment_start DESC LIMIT 1;
    IF NOT v_ok THEN
        RAISE EXCEPTION 'E failed: restoring the original columns did not restore the chain '
                        '(% is not the identity of recomputation) - the payload and the '
                        'repair disagree about what was hashed', v_why;
    END IF;
    v_n := v_n + 1;

    ------------------------------------------------------------------
    -- F. the rollup 6.2 found unwired: refresh, replay, and the B24 debt paid. Pattern 1
    --    means the replay returns the same answer from the natural key, not a double count.
    ------------------------------------------------------------------
    INSERT INTO human_sessions (user_id, user_name, bot_id, bot_type, session_status,
                                login_time, logout_time)
         VALUES ('0013-probe-user', 'probe', '0013-probe-bot', 'customer_service',
                 'completed', now() - interval '30 minutes', now() - interval '2 minutes')
      RETURNING session_id INTO v_sess;
    INSERT INTO bot_actions (session_id, user_id, bot_id, action_type, success)
         VALUES (v_sess, '0013-probe-user', '0013-probe-bot', 'lookup', true),
                (v_sess, '0013-probe-user', '0013-probe-bot', 'update', false);

    v_rows := audit_summary_refresh(current_date);
    UPDATE audit_summary SET updated_at = '2000-01-01T00:00:00Z'
     WHERE user_id = '0013-probe-user' AND "date" = current_date;
    v_rows := audit_summary_refresh(current_date);      -- replay: pattern 1 same answer
    IF (SELECT count(*) FROM audit_summary
         WHERE user_id = '0013-probe-user' AND "date" = current_date) <> 1 THEN
        RAISE EXCEPTION 'F failed: the replay created % rows for one key - the upsert is not '
                        'arbitrating on the tenant-scoped unique',
                        (SELECT count(*) FROM audit_summary
                          WHERE user_id = '0013-probe-user' AND "date" = current_date);
    END IF;
    IF (SELECT updated_at > '2000-01-02T00:00:00Z' FROM audit_summary
         WHERE user_id = '0013-probe-user' AND "date" = current_date) IS NOT TRUE THEN
        RAISE EXCEPTION 'F failed: the rollup was rewritten while its updated_at stayed put - '
                        'this is exactly the B24 disagreement 0010 told this file to avoid';
    END IF;
    IF (SELECT needs_attention FROM vw_timestamp_status WHERE table_name = 'audit_summary')
        IS NOT FALSE THEN
        RAISE EXCEPTION 'F failed: vw_timestamp_status still says audit_summary''s rewrite '
                        'goes unrecorded - the register''s evidence and verdict diverged';
    END IF;
    IF (SELECT count(*) FROM audit_log WHERE table_name = 'audit_summary'
         AND row_pk->>'summary_id' = (SELECT summary_id::text FROM audit_summary
                                       WHERE user_id = '0013-probe-user'
                                         AND "date" = current_date)) <> 3 THEN
        RAISE EXCEPTION 'F failed: the rollup''s own history (create, pin, replay) left % '
                        'trail rows, expected 3 - wired to the tables but not to the trail '
                        'is still 6.2''s finding',
                        (SELECT count(*) FROM audit_log WHERE table_name = 'audit_summary'
                          AND row_pk->>'summary_id' = (SELECT summary_id::text
                                                        FROM audit_summary
                                                       WHERE user_id = '0013-probe-user'
                                                         AND "date" = current_date));
    END IF;
    v_n := v_n + 1;

    ------------------------------------------------------------------
    -- G. two tenants, two chains, one interleaved history. Written as afpc_app with the
    --    tenant GUC switched mid-transaction: the chain head lookup is tenant-filtered, so
    --    a global ORDER BY audit_id DESC would have read the other tenant''s head while
    --    showing zero visible rows (0011''s lost-write bug, chain edition) - the segment
    --    per tenant makes the invisible row structurally irrelevant.
    ------------------------------------------------------------------
    v_t2 := afpc_uuid_v7();
    INSERT INTO tenants (tenant_id, name, slug)
         VALUES (v_t2, '0013 chain probe', '0013-chain-probe');

    PERFORM set_config('app.tenant_id', v_t2::text, true);
    INSERT INTO entities (name, entity_type) VALUES ('0013 probe G tenant 2', 'customer');
    PERFORM set_config('app.tenant_id', v_t1::text, true);
    INSERT INTO entities (name, entity_type) VALUES ('0013 probe G tenant 1', 'customer');
    PERFORM set_config('app.tenant_id', v_t2::text, true);
    INSERT INTO entities (name, entity_type) VALUES ('0013 probe G2 tenant 2', 'customer');
    PERFORM set_config('app.tenant_id', v_t1::text, true);

    SELECT count(*) INTO v_rows FROM audit_chain_verify(v_t2) WHERE NOT chain_ok;
    IF v_rows <> 0 THEN
        RAISE EXCEPTION 'G failed: tenant 2''s chain does not verify although tenant 1 wrote '
                        'between its rows - the segments are not independent';
    END IF;
    SELECT count(*) INTO v_rows FROM audit_chain_verify(v_t1) WHERE NOT chain_ok;
    IF v_rows <> 0 THEN
        RAISE EXCEPTION 'G failed: tenant 1''s chain broke under the same interleave';
    END IF;
    v_n := v_n + 1;

    ------------------------------------------------------------------
    -- H. the register classifies the new machinery correctly: the rollup is pattern 1 by
    --    its own text, the audit trigger is not an operation at all, and nothing in this
    --    file's functions is listed UNGUARDED - the exclusion 0013 made must be observable,
    --    not promised.
    ------------------------------------------------------------------
    IF NOT EXISTS (SELECT 1 FROM vw_idempotency_status
                    WHERE function = 'audit_summary_refresh'
                      AND verdict LIKE 'ADR-005 pattern 1%') THEN
        RAISE EXCEPTION 'H failed: audit_summary_refresh is not classified pattern 1 - the '
                        'register stopped reading bodies (0011''s probe J failure mode)';
    END IF;
    IF EXISTS (SELECT 1 FROM vw_idempotency_status WHERE function = 'afpc_audit_row') THEN
        RAISE EXCEPTION 'H failed: the trigger function is in the operations register - the '
                        'return-type exclusion did not survive the transform';
    END IF;
    v_n := v_n + 1;

    ------------------------------------------------------------------
    -- Cleanup: fixtures go, the trail about them stays (deletes are writes; a trail that
    -- vanished with the rows it described would not be evidence). Then the chain must
    -- still verify - including over the cleanup, which is the property that makes the
    -- sentence in this comment legal. The probe TENANT is the exception, and its handling
    -- is a finding: audit rows FK to tenants with RESTRICT, and deleting the tenants row
    -- would itself fire an audit insert referencing the tenant being deleted - so a hard
    -- delete of a tenant is atomic-impossible by ordinary SQL, by design (a tenant with
    -- history cannot vanish; 'archived' exists in tenants.status for exactly that). The
    -- controlled owner operation below is the only sanctioned erasure: segment first,
    -- tenant second, trigger firing off - the same primitive 0019's partition detach
    -- will formalise, and one reason the segment boundary is (tenant, month).
    ------------------------------------------------------------------
    DELETE FROM bot_actions  WHERE user_id = '0013-probe-user';
    DELETE FROM human_sessions WHERE user_id = '0013-probe-user';
    DELETE FROM audit_summary WHERE user_id = '0013-probe-user';
    DELETE FROM entities WHERE name IN ('0013 probe G tenant 1', '0013 probe B renamed');
    EXECUTE 'SET LOCAL session_replication_role = replica';
    DELETE FROM entities WHERE tenant_id = v_t2;
    DELETE FROM audit_log  WHERE tenant_id = v_t2;
    DELETE FROM tenants    WHERE tenant_id = v_t2;
    EXECUTE 'RESET session_replication_role';
    IF (SELECT count(*) FROM audit_chain_verify(v_t1) WHERE NOT chain_ok) <> 0 THEN
        RAISE EXCEPTION 'cleanup failed: the chain does not verify after the probes are '
                        'undone - trail or repair is lying about one of them';
    END IF;
    IF (SELECT count(*) FROM audit_log WHERE tenant_id = v_t2) <> 0
       OR EXISTS (SELECT 1 FROM tenants WHERE tenant_id = v_t2) THEN
        RAISE EXCEPTION 'cleanup failed: probe residue remains in audit_log or tenants';
    END IF;

    IF v_n <> 8 THEN
        RAISE EXCEPTION 'expected 8 behavioural verifications, completed %', v_n;
    END IF;
    RAISE NOTICE '6.2: % checks passed - ordinary writes are trailed exactly, history cannot '
                 'be rewritten by any application role and tampering by one that can is '
                 'exposed by the chain, two tenants chain independently, and the rollup is '
                 'wired with its timestamp debt paid', v_n;
END
$$;

