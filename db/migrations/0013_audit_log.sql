-- 0013: the row-level audit trail, append-only by grant, tamper-evident by chain
--       (DATABASE_REVIEW.md 6.2; ADR-005-adjacent, review 2.6's prescription)
--
-- 6.2's finding, restated after re-measuring: the canonical schema's only history was
-- audit_summary, a rollup no function wrote (measured at 0011: zero hits for
-- 'audit_summary' in pg_proc besides this file's own future additions - the table was
-- furniture), and the row-level log the review knew of lived in the vestigial schema that
-- 0001 deliberately did not port. So this migration builds the thing from the pattern the
-- other fifteen migrations established: catalog-derived scope, behaviour asserted by
-- probes, the register published as a view.
--
-- What 2.6 asked for, line by line:
--   * "row-level ... in the canonical schema" - audit_log, public, one row per row-change.
--   * "no UPDATE/DELETE grants" - the mechanism that binds every role the application can
--     connect as, including afpc_app with its DML defaults (0002 grants four privileges
--     forward; here the new table declines two of them by name). Honest limit, stated
--     rather than skipped: a superuser can still rewrite rows, which is exactly why the
--     two mechanisms are paired - the grants PREVENT the write paths, the chain EXPOSES
--     whoever bypasses them, and probe E exercises that path for real and repairs it.
--   * "hash chain" - per (tenant, calendar-month) segments, sha256 over a canonical jsonb
--     payload with the previous row's hash as prefix. Per-tenant because 0009's wall binds
--     an afpc_app chain walk to its own tenant (a global chain's head would be
--     invisible-cross-tenant - the same class of bug 0011 measured when a global claim
--     index answered INSERT 0 0); by month because 6.6's retention answer is DETACH, and a
--     segment is a detachable unit of chain. A chain that partition-detach can break is a
--     chain that was never tamper-evident.
--   * "monthly-partitioned" - deliberately NOT here: that is 0019's decision for every
--     append-only table at once, made once with the real volumes. The segment boundary is
--     chosen so partitioning audit_log later is mechanical, not a re-design.
--
-- Scope, derived not listed: every tenant-coded base table gets the trigger except two,
-- each with a reason the coverage view publishes. audit_log cannot audit itself (the
-- insert would fire the trigger that inserts). idempotency_keys is excluded as transient
-- mechanism state - its TTL'd rows are themselves the audit evidence of a claim, and
-- logging the logging guard doubles every write's bookkeeping to protect a table whose
-- contents nobody claims are history. The telemetry tables (bot_actions, human_sessions,
-- agent_interactions) are IN scope, which 6.2 demands as loudly as the CRM tables: their
-- rows are what an auditor cross-checks the trail against, and 5.8's "no immutability
-- mechanism anywhere" does not stop at the business tables.
--
-- Identity, the half of 5.8 this file was told to decide: no new actors registry. audit_log
-- records db_user (current_user - resolvable in pg_authid, so a fact, not free text) and
-- tenant_id (FK). A users/principals table nothing connects as would recreate §3.1's twin
-- problem with more tables; the registry lands with the code that authenticates against it.
-- This is the reason 0009's "row security binds a role" note is the honest answer to 2.2 for
-- now, and where it is not enough, the gap is vw_audit_coverage's decision column.

SET client_min_messages TO notice;

-- ---------------------------------------------------------------------------
-- 1. The log itself
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS audit_log (
    audit_id    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id   uuid        NOT NULL DEFAULT afpc_current_tenant(),
    table_name  text        NOT NULL,
    row_pk      jsonb       NOT NULL,
    action      text        NOT NULL
        CONSTRAINT audit_log_action_allowed CHECK
        (action IN ('INSERT', 'UPDATE', 'DELETE')),
    old_values  jsonb,
    new_values  jsonb,
    db_user     text        NOT NULL DEFAULT current_user,
    occurred_at timestamptz NOT NULL DEFAULT now(),
    prev_hash   text        NOT NULL,
    row_hash    text        NOT NULL
);

-- bigint identity, not uuid: review 2.7's own rule - time-ordered keys for append-only
-- ledgers - and the chain walks by this column, so its order is its correctness. BY DEFAULT,
-- not ALWAYS: the trigger draws nextval() under the segment lock and inserts the value
-- explicitly, because the hash must cover the row's position (ALWAYS would reject exactly
-- that, a detail only a rehearsal meets). A role that could insert a hand-made id out of
-- order would break prev_hash, not get past it. The sequence's privileges are asserted in
-- section 3 rather than trusted from 0002's defaults: an identity sequence is created as
-- part of the table, and whether the default-privileges record fires for it is the kind of
-- thing this project has learned to check (B23's lesson).

COMMENT ON TABLE audit_log IS
    'Row-level, append-only change history - the mechanism 6.2 found missing. One row per '
    'INSERT/UPDATE/DELETE on every tenant-coded table except audit_log (recursion) and '
    'idempotency_keys (transient state; see vw_audit_coverage for the register and reasons). '
    'Append-only by GRANT (no UPDATE/DELETE/TRUNCATE to any role but the owner - a superuser '
    'bypass is EXPOSED, not prevented, which is what the hash chain is for) and tamper-evident '
    'per (tenant, month) segment: row_hash = sha256(prev_hash || canonical payload), genesis '
    'hash derived from the segment identity, so nothing external has to be trusted. '
    'UPDATE stores only the changed columns in old/new (vectors as ''<vector omitted>'' - '
    'their stringification costs 60x the rest of an audit row, measured). row_pk is the '
    'primary key as {column: value} jsonb: polymorphic by necessity across 18+ tables, '
    'which review 3.x calls unenforceable and 6.6 will make prunable; here it is an evidence '
    'field, not a join. Built by 0013.';

COMMENT ON COLUMN audit_log.db_user IS
    'The effective PostgreSQL role that wrote the row - current_user, so SET LOCAL ROLE '
    'changes are recorded as the seat actually sat in. Not free text: resolvable in '
    'pg_authid. The application-identity half (which human, which agent) lands with the '
    'registry that can authenticate it (5.8 identity half, decided here: no table of '
    'unvalidated principal names, which is what 5.8 justly criticised 13 actor columns for).';

COMMENT ON COLUMN audit_log.row_pk IS
    'The changed row''s primary key as a one-entry jsonb object {column: value}. Generic on '
    'purpose: the trail must outlive key widening the way 0005 just performed it, and a '
    'typed bigint column would have gone stale three migrations ago. Not an FK - no FK can '
    'span 18 targets; the coverage view, not a constraint, answers "is this row audited".';

-- ---------------------------------------------------------------------------
-- 2. The chain: genesis, hashing, and the trigger that writes both
-- ---------------------------------------------------------------------------
-- A plain table default cannot see the previous row under concurrency, so the chain lives
-- in the trigger that inserts. The helper takes the WHOLE future row as a typed parameter,
-- which means the trigger and the verifier hash exactly the same expression by
-- construction - two definitions of "the payload" is how a chain becomes folklore (B25's
-- principle, applied to a hash instead of a trigger body).

CREATE OR REPLACE FUNCTION afpc_audit_genesis(p_tenant uuid, p_month timestamptz)
RETURNS text LANGUAGE sql IMMUTABLE AS
$$ SELECT encode(digest('AFPC-AUDIT-GENESIS' || p_tenant || p_month, 'sha256'), 'hex') $$;

CREATE OR REPLACE FUNCTION afpc_audit_hash(r audit_log)
RETURNS text LANGUAGE sql IMMUTABLE AS
$$
    SELECT encode(
        digest(
            coalesce(r.prev_hash, afpc_audit_genesis(r.tenant_id,
                     date_trunc('month', r.occurred_at)))
            || jsonb_build_object(
                 'id',      r.audit_id,
                 'tenant',  r.tenant_id,
                 'table',   r.table_name,
                 'pk',      r.row_pk,
                 'action',  r.action,
                 'old',     r.old_values,
                 'new',     r.new_values,
                 'user',    r.db_user,
                 'at',      r.occurred_at
               )::text,
            'sha256'),
        'hex')
$$;

CREATE OR REPLACE FUNCTION afpc_audit_row() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    v_row    jsonb;
    v_older  jsonb;
    v_tenant uuid;
    v_old    jsonb;
    v_new    jsonb;
    v_pk     jsonb;
    v_pkcols text;
    v_month  timestamptz := date_trunc('month', now());
    v_prev   text;
    v_id     bigint;
    v_hash   text;
    v_rec    record;
BEGIN
    IF TG_OP IN ('INSERT', 'UPDATE') THEN
        v_row := to_jsonb(NEW);
    ELSE
        v_row := to_jsonb(OLD);
    END IF;
    IF TG_OP = 'UPDATE' THEN
        v_older := to_jsonb(OLD);
    END IF;

    -- Vector columns: dropped from what the audit row STORES (their text rendering is 60x
    -- the rest of an audit row's work, measured at 0.09 ms vs 0.0015 ms per row, and no
    -- auditor compares coordinate lists), but a real change is still recorded, as a
    -- sentinel on both sides. The detoast inside to_jsonb is the price of one generic
    -- trigger for nineteen tables; stated, not hidden.
    FOR v_rec IN
        SELECT attname FROM pg_attribute
         WHERE attrelid = TG_RELID AND atttypid = 'vector'::regtype AND attnum > 0
    LOOP
        IF v_row ? v_rec.attname THEN
            IF TG_OP = 'UPDATE' AND (v_row -> v_rec.attname)
                  IS DISTINCT FROM (v_older -> v_rec.attname) THEN
                v_new := jsonb_build_object(v_rec.attname, '<vector omitted>');
                v_old := jsonb_build_object(v_rec.attname, '<vector omitted>');
            END IF;
            v_row   := v_row   - v_rec.attname;
            v_older := coalesce(v_older, '{}'::jsonb) - v_rec.attname;
        END IF;
    END LOOP;

    v_tenant := (v_row ->> 'tenant_id')::uuid;
    IF v_tenant IS NULL THEN
        RAISE EXCEPTION 'audit trigger on %.%: the row resolved to no tenant_id - the '
                        'census attached this trigger to a table outside its own definition '
                        'of tenant-coded', TG_TABLE_SCHEMA, TG_TABLE_NAME;
    END IF;

    -- row_pk BEFORE tenant_id is stripped: tenants' primary key IS tenant_id, so the
    -- general rule (keys come from pg_index) has to run against the unpruned row.
    SELECT string_agg(a.attname, ',' ORDER BY k.ord)
      INTO v_pkcols
      FROM unnest((SELECT indkey FROM pg_index
                    WHERE indrelid = TG_RELID AND indisprimary)::int[])
           WITH ORDINALITY AS k(attnum, ord)
      JOIN pg_attribute a ON a.attrelid = TG_RELID AND a.attnum = k.attnum::smallint;
    SELECT jsonb_object_agg(col, v_row -> col) INTO v_pk
      FROM unnest(string_to_array(v_pkcols, ',')) AS col;

    v_row := v_row - 'tenant_id';

    IF TG_OP = 'UPDATE' THEN
        -- changed columns only, both sides; a no-op rewrite still logs an action row
        -- (6.3's distinction inherited: the row WAS written; whether anything differs is a
        -- separate question the old/new pair answers by being empty)
        FOR v_rec IN SELECT key FROM jsonb_each(v_row)
        LOOP
            IF (v_row -> v_rec.key) IS DISTINCT FROM (v_older -> v_rec.key) THEN
                v_new := coalesce(v_new, '{}'::jsonb) ||
                         jsonb_build_object(v_rec.key, v_row -> v_rec.key);
                v_old := coalesce(v_old, '{}'::jsonb) ||
                         jsonb_build_object(v_rec.key, v_older -> v_rec.key);
            END IF;
        END LOOP;
    ELSIF TG_OP = 'INSERT' THEN
        v_new := v_row;
    ELSE
        v_old := v_row;
    END IF;

    -- Serialize the segment. The lock IS the lock table (0011's lesson restated): a
    -- row-lookup-based chain head would be invisible cross-tenant under RLS exactly when
    -- another tenant had just written, and the advisory key names no rows for a policy to
    -- hide. xact-scoped: held through the insert, released by commit or abort, so a rolled
    -- back audit attempt never advances the chain and never wedges it.
    PERFORM pg_advisory_xact_lock(
        hashtextextended(v_tenant::text ||
                         extract(epoch from v_month)::bigint::text, 0));

    SELECT row_hash INTO v_prev
      FROM audit_log
     WHERE tenant_id = v_tenant
       AND occurred_at >= v_month AND occurred_at < v_month + interval '1 month'
     ORDER BY audit_id DESC
     LIMIT 1;
    v_prev := coalesce(v_prev, afpc_audit_genesis(v_tenant, v_month));

    -- The id is drawn here (under the lock, so segment order and key order agree) purely so
    -- the hash covers it: a chain that did not include its own position could be reordered
    -- wholesale - same hashes, different history - by a writer who could rewrite rows.
    v_id := nextval('audit_log_audit_id_seq');

    v_hash := afpc_audit_hash(ROW(v_id, v_tenant, TG_TABLE_NAME, v_pk, TG_OP,
                                  NULLIF(v_old, '{}'::jsonb), NULLIF(v_new, '{}'::jsonb),
                                  current_user, now(), v_prev, NULL)::audit_log);

    INSERT INTO audit_log (audit_id, tenant_id, table_name, row_pk, action,
                           old_values, new_values, db_user, occurred_at,
                           prev_hash, row_hash)
    VALUES (v_id, v_tenant, TG_TABLE_NAME, v_pk, TG_OP,
            NULLIF(v_old, '{}'::jsonb), NULLIF(v_new, '{}'::jsonb),
            current_user, now(), v_prev, v_hash);

    RETURN NULL;   -- AFTER-row: the returned record is ignored
END
$$;

-- ---------------------------------------------------------------------------
-- 3. Attach, by census; privileges, by exception; the wall, by 0009's shape
-- ---------------------------------------------------------------------------
DO $$
DECLARE
    t record;
    n int := 0;
BEGIN
    FOR t IN
        SELECT c.relname
          FROM pg_class c
          JOIN pg_namespace ns ON ns.oid = c.relnamespace
          JOIN pg_attribute a ON a.attrelid = c.oid
                             AND a.attname = 'tenant_id' AND a.attnum > 0
                             AND NOT a.attisdropped
         WHERE ns.nspname = 'public' AND c.relkind = 'r'
           AND c.relname <> 'schema_migrations'
           AND c.relname NOT IN ('audit_log', 'idempotency_keys')
         ORDER BY c.relname
    LOOP
        EXECUTE format('DROP TRIGGER IF EXISTS afpc_audit_row ON public.%I', t.relname);
        EXECUTE format($f$CREATE TRIGGER afpc_audit_row
                AFTER INSERT OR UPDATE OR DELETE ON public.%I
                FOR EACH ROW EXECUTE FUNCTION afpc_audit_row()$f$, t.relname);
        n := n + 1;
    END LOOP;
    RAISE NOTICE '6.2: audit trigger attached to % tenant-coded tables (census-derived: '
                 'every relkind=r table with a tenant_id, minus the two declared exemptions '
                 'vw_audit_coverage publishes)', n;
END
$$;

-- Append-only, the way 2.6 prescribed: by grant. 0002's forward defaults landed afpc_app
-- arwd on this brand-new table (that is the mechanism working as designed); declining the
-- two history-altering privileges is this migration's exception, asserted in the probes
-- rather than assumed. A superuser can still rewrite rows - no grant structure stops the
-- account that owns the cluster - which is exactly why this migration ships two mechanisms
-- where 6.2 asked for one: grants PREVENT on every path an agent can connect as, the chain
-- EXPOSES whatever bypasses them (probe E exercises the bypass for real, on purpose).
REVOKE UPDATE, DELETE, TRUNCATE ON audit_log FROM afpc_app;
REVOKE UPDATE, DELETE, TRUNCATE ON audit_log FROM PUBLIC;

-- B23's lesson applied to an identity sequence: an IDENTITY's sequence is created inside
-- CREATE TABLE, and whether 0002's default-privileges record fires for it is a fact to
-- check, not a property to trust. Granted explicitly; the probe asserts it from the ACL.
GRANT USAGE, SELECT ON SEQUENCE audit_log_audit_id_seq TO afpc_app;

-- 0009's exact shape, by hand: B7's scope is catalog-derived, so this table enrolls itself
